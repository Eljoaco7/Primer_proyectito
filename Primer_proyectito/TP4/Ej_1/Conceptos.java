package Primer_proyectito.TP4.Ej_1;

public class Conceptos {
   /* a) Encapsular es agrupar datos y operaciones en una clase y ocultar la
   representación interna y la implementación, exponiendo solo una interfaz de
   servicios (se sabe qué hace, no cómo). Java lo permite con los modificadores
   de acceso (public, private, protected)

   b) Ventajas: los cambios de implementación 
   no afectan a los clientes, y la clase controla que su estado
   sea válido. Si los atributos no se encapsulan, cualquier cliente puede
   modificarlos directamente dejando al objeto en un estado que no queremos, y
   además queda acoplado a la representación, así que cambiarla rompe a todos
   los clientes.

   c) Un TDA es un tipo definido por sus valores y operaciones, especificados
   por su comportamiento con independencia de la representación. La clase
   implementa el TDA y el cliente lo usa solo a través de su interfaz. */
}
